export function marketingText(text: string, locale: SeoLocale): string {
  if (locale !== "hi") return text;
  const trimmed = text.trim();
  const translated = MARKETING_COPY[trimmed];
  if (!translated) return text;
  const leading = text.match(/^\s*/)?.[0] || "";
  const trailing = text.match(/\s*$/)?.[0] || "";
  return `${leading}${translated}${trailing}`;
}

function localizeNode(node: ReactNode, locale: SeoLocale): ReactNode {
  if (typeof node === "string") return marketingText(node, locale);
  if (typeof node === "number" || node == null || typeof node === "boolean") return node;
  if (Array.isArray(node)) return node.map((child) => localizeNode(child, locale));
  if (!isValidElement<Record<string, unknown>>(node)) return node;
  const props: Record<string, unknown> = {};
  for (const [key, value] of Object.entries(node.props)) {
    if (key === "children") props.children = localizeNode(value as ReactNode, locale);
    else if (key === "href" && typeof value === "string" && locale === "hi") {
      const match = value.match(/^(\/(?:features|how-it-works|pricing|plans\/[^/?#]+|about|demo|privacy|terms|refund|reseller-terms)?)([?#].*)?$/);
      props[key] = match ? `/hi${match[1] === "/" ? "" : match[1]}${match[2] || ""}` : value;
    }
    else if (typeof value === "string") props[key] = marketingText(value, locale);
    else if (Array.isArray(value) || isValidElement(value)) props[key] = localizeNode(value as ReactNode, locale);
    else props[key] = value;
  }
  return cloneElement(node, props);
}

export function LocalizedCopy({ locale, children }: { locale: SeoLocale; children: ReactNode }) {
  return <>{localizeNode(children, locale)}</>;
}
